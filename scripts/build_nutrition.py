#!/usr/bin/env python3
"""Replay the reviewed calorie scenarios; no network access or fuzzy matching.

Normal rebuild: python3 scripts/build_nutrition.py
Optional profile extraction: --fndds /path/to/USDA/surveyDownload.json
Checks: --check compares every generated byte without writing anything.
"""
import argparse
import csv
import hashlib
import html
import io
import json
import math
import re
import subprocess
from pathlib import Path

from nutrition_models import ROOT, ROWS, IDS, MODELS, INVENTORY_SHA256

DATE = '2026-10-26'
PROFILE_PATH = ROOT / 'data/nutrition/profiles.json'
BEGIN = '/* BEGIN GENERATED CALORIE DATA */'
END = '/* END GENERATED CALORIE DATA */'
USDA = 'https://fdc.nal.usda.gov/download-datasets/'
CONCH_URL = 'https://www.ars.usda.gov/ARSUserFiles/80400535/Data/SR/SR28/reports/sr28fg15.pdf#page=678'
COCKTAIL_URL = 'https://www.beaches.com/blog/beaches-cocktail-recipes/'
GUEST_URL = 'https://shorelinejourneys.com/beaches-turks-and-caicos-dining-guide/'

def encoded(data, compact=False):
    return json.dumps(data, ensure_ascii=False, indent=None if compact else 2,
                      separators=(',',':') if compact else None, allow_nan=False) + '\n'

def extract_profiles(source):
    raw = source.read_bytes()
    foods = {f['fdcId']: f for f in json.loads(raw)['SurveyFoods']}
    profiles = {}
    used = {c['profile'] for m in MODELS.values() for c in m.get('components', [])}
    for key in sorted(used - {'conch'}):
        f = foods[IDS[key]]
        kcal = [n['amount'] for n in f['foodNutrients'] if n['nutrient']['id'] == 1008]
        if len(kcal) != 1: raise ValueError(f'Energy missing/duplicated: {key}')
        profiles[key] = {'fdc_id':f['fdcId'], 'description':f['description'],
                         'kcal_per_100g':kcal[0], 'source_url':f"https://fdc.nal.usda.gov/food-details/{f['fdcId']}/nutrients",
                         'basis':'USDA FNDDS 2021-2023 generic food, per 100 g edible portion; not a Beaches recipe.'}
    profiles['conch'] = {'fdc_id':173720,'description':'Mollusks, conch, baked or broiled',
        'kcal_per_100g':130,'source_url':CONCH_URL,
        'basis':'USDA SR28 (2015), NDB 15250, page 678: energy 130 kcal per 100 g. Cooked proxy even for citrus-marinated dishes.'}
    return {'schema_version':1, 'dataset':'USDA FNDDS 2021-2023, October 2024 release; conch from SR28',
            'dataset_source':USDA, 'fndds_sha256':hashlib.sha256(raw).hexdigest(),
            'review_date':DATE,'profiles':profiles}

def round_kcal(value, direction='nearest'):
    # Very small unsweetened drinks remain visible as <10 rather than fictitious zero.
    fn = {'nearest':lambda x:math.floor(x+.5),'low':math.floor,'high':math.ceil}[direction]
    return int(fn(value/10)*10)

def build(profile_data):
    current = json.loads(subprocess.check_output(['node', str(ROOT / 'scripts/menu_inventory.cjs')]))
    if current != ROWS: raise ValueError('Live menu differs from the pinned inventory; review models before rebuilding')
    if set(MODELS) != set(range(len(ROWS))): raise ValueError('Every menu row needs an explicit estimate or withholding decision')
    profiles = profile_data['profiles']
    for key,p in profiles.items():
        if not math.isfinite(p['kcal_per_100g']) or not 0 < p['kcal_per_100g'] <= 1000:
            raise ValueError(f'Invalid source energy {key}')
        if not p['source_url'].startswith('https://') or not p['description'] or not p['basis']:
            raise ValueError(f'Missing profile provenance {key}')
        if key != 'conch' and p['fdc_id'] != IDS[key]: raise ValueError(f'Profile ID changed {key}')
    rows=[]
    for i,base in enumerate(ROWS):
        m=MODELS[i]
        row=dict(base, review_date=DATE)
        # Original menu snapshot retained; this pass does not assert every old PDF is current.
        row['menu_evidence_status']='Existing menu-book snapshot; full inventory not refreshed in this calorie pass'
        row['ingredient_source'] = GUEST_URL if base['guest'] else base['menu_source']
        if base['venue_id']=='drinks':
            row['ingredient_source'] = COCKTAIL_URL if i in (511,512,513,514,515) else ('https://www.beaches.com/all-inclusive/premium-drinks/' if i <= 510 else None)
            if i >= 526:
                row['ingredient_source']='https://stuffedsuitcase.com/paradise-cheers-7-hidden-drinks-at-beaches-turks-caicos/'
                row['guest']=True
        if 'withheld_reason' in m:
            row.update(status='unavailable',grade=None,kcal=None,kcal_low=None,kcal_high=None,
                       withheld_reason=m['withheld_reason'],components=[])
        else:
            parts=[]
            for c in m['components']:
                p=profiles[c['profile']]
                if len(c['grams'])!=3 or not 0<=c['grams'][0]<=c['grams'][1]<=c['grams'][2] or c['grams'][1]<=0:
                    raise ValueError(f'Bad component scenario {base["id"]}')
                parts.append(dict(c, kcal=[round(g*p['kcal_per_100g']/100,6) for g in c['grams']]))
            totals=[math.fsum(c['kcal'][j] for c in parts) for j in range(3)]
            note=m['note']
            if any(c['profile']=='spirit' for c in parts):
                note += ' Generic USDA rum energy proxies distilled spirits; actual product strength/pour is unverified.'
            row.update(status='modeled',grade='D',serving=m['serving'],note=note.strip(),components=parts,
                       kcal=round_kcal(totals[1]),kcal_low=round_kcal(totals[0],'low'),
                       kcal_high=round_kcal(totals[2],'high'), kcal_unrounded=totals,
                       assumed_edible_g=[round(math.fsum(c['grams'][j] for c in parts),1) for j in range(3)])
        rows.append(row)
    if len({r['id'] for r in rows}) != len(rows): raise ValueError('Duplicate menu identity')
    modeled=sum(r['status']=='modeled' for r in rows)
    meta={'review_date':DATE,'inventory_sha256':INVENTORY_SHA256,'menu_rows':len(rows),
          'modeled':modeled,'unavailable':len(rows)-modeled,'grade':'D = Use with caution; evidence quality, not healthfulness',
          'basis':'Hypothetical component weights × USDA energy per 100 g; all portions modeled, none weighed.',
          'range':'Low/high portion scenarios, generally 65%/150% of central component weights unless explicitly bounded. Not a confidence interval or guaranteed limits; actual food can fall outside.',
          'rounding':'Central rounded to nearest 10 kcal; lower rounded down and upper up to 10. Values below 10 displayed as <10.',
          'scope':'Existing menu-book inventory only. No official Beaches calorie declarations used; no current-menu guarantee; buffets without itemized food have no estimate.',
          'sources':[USDA,'https://www.beaches.com/resorts/turks-caicos/restaurants/',COCKTAIL_URL,CONCH_URL]}
    return {'schema_version':1,'metadata':meta,'profiles':profiles,'items':rows}

def report_html(data):
    esc=html.escape
    trs=[]
    for r in data['items']:
        modeled=r['status']=='modeled'
        display=f"{'<10' if r['kcal']<10 else '~'+str(r['kcal'])} kcal ({r['kcal_low']}–{r['kcal_high']}) · D" if modeled else 'Estimate unavailable'
        detail=(r['serving']+'. '+r['note']) if modeled else r['withheld_reason']
        components='; '.join(f"{data['profiles'][c['profile']]['description']}: {c['grams'][1]:g} g ({c['grams'][0]:g}–{c['grams'][2]:g})" for c in r['components'])
        src=r['ingredient_source']
        trs.append(f'<tr><td>{esc(r["venue"])}</td><td>{esc(r["menu"])}</td><td><b>{esc(r["name"])}</b><br>{esc(r["description"])}</td><td>{esc(display)}</td><td>{esc(detail)}'+(f'<details><summary>Component assumptions</summary>{esc(components)}</details>' if components else '')+(f'<br><a href="{esc(src)}">Menu/ingredient source</a>' if src else '')+'</td></tr>')
    m=data['metadata']
    return '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Beaches calorie estimates</title><style>body{font:16px/1.5 system-ui;background:#f2f6f4;color:#0f2a31;margin:24px}main{max-width:1500px;margin:auto}a{color:#096d73}table{border-collapse:collapse;width:100%;background:white}th,td{text-align:left;vertical-align:top;padding:12px;border:1px solid #ccd9d5}th{background:#dcebe6}td:nth-child(4){min-width:130px}details{margin-top:8px;font-size:14px}header{max-width:850px} .scroll{overflow:auto}input{font:inherit;padding:10px;width:min(90%,600px);margin:12px 0}p{max-width:90ch}@media print{input{display:none}body{margin:0;font-size:10px}}</style><main><header><h1>Beaches calorie estimates</h1><p>Prepared '+DATE+' · '+str(m['modeled'])+' modeled entries · '+str(m['unavailable'])+' unavailable · '+str(m['menu_rows'])+' menu rows reviewed.</p><p><b>Every numeric entry is Grade D: use with caution.</b> These are assumptions based on menu descriptions and generic USDA foods, not official Beaches nutrition. Grades describe evidence quality, not healthfulness. Portions were not weighed.</p><p>Ranges show low/high scenarios, not statistical confidence limits. Actual portions or recipes can fall outside. Pizza is a whole assumed individual pizza, sushi rolls are four pieces, and the shared steak is per person. Read each serving before comparing. Old menus and guest reports may be outdated.</p><p><a href="../../index.html">Open the menu website preview</a> · <a href="../../data/nutrition/estimates.json">Full audit data</a> · <a href="../../data/nutrition/methodology.txt">Method and sources</a></p></header><label for="q">Find a dish or restaurant</label><br><input id="q" type="search" placeholder="e.g. salmon, Butch, taco"><div class="scroll"><table><thead><tr><th>Restaurant</th><th>Menu</th><th>Dish</th><th>Calories</th><th>Serving and limitations</th></tr></thead><tbody>'+''.join(trs)+'</tbody></table></div></main><script>document.querySelector("#q").addEventListener("input",e=>{const q=e.target.value.toLowerCase();document.querySelectorAll("tbody tr").forEach(r=>r.hidden=!r.textContent.toLowerCase().includes(q))})</script></html>\n'

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--fndds',type=Path)
    ap.add_argument('--check',action='store_true')
    args=ap.parse_args()
    profiles=extract_profiles(args.fndds) if args.fndds else json.loads(PROFILE_PATH.read_text())
    data=build(profiles)
    # Keep display data embedded in the network-first HTML for consistent offline updates.
    display={'metadata':data['metadata'],'profiles':data['profiles'],
             'items':{r['id']:{k:v for k,v in r.items() if k in ('status','grade','serving','note','components','kcal','kcal_low','kcal_high','withheld_reason','ingredient_source','guest','menu_date','menu_evidence_status')} for r in data['items']}}
    generated=BEGIN+'\nconst CALORIES = '+encoded(display,True).strip().replace('<','\\u003c')+';\n'+END
    index=ROOT/'index.html'
    page=index.read_text()
    if BEGIN not in page:
        page=page.replace('/* ---------- data ---------- */','/* ---------- data ---------- */\n'+BEGIN+'\n'+END)
    page,n=re.subn(re.escape(BEGIN)+r'.*?'+re.escape(END),lambda _:generated,page,flags=re.S)
    if n!=1: raise ValueError('Generated calorie marker missing or duplicated')
    out={PROFILE_PATH:encoded(profiles),ROOT/'data/nutrition/estimates.json':encoded(data),
         ROOT/'deliverables/nutrition/beaches-calorie-estimates.html':report_html(data),index:page}
    for p,content in out.items():
        if args.check:
            if not p.exists() or p.read_text()!=content: raise SystemExit(f'Stale generated file: {p.relative_to(ROOT)}')
        else:
            p.parent.mkdir(parents=True,exist_ok=True);p.write_text(content)
    print(encoded(data['metadata']))

if __name__=='__main__': main()
